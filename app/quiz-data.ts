export interface QuizSetAnswer {
  a: number | null;
  b: number | null;
}

export function isQuizSetCorrect(set: QuizSet, answer: QuizSetAnswer | undefined): boolean {
  if (!answer || answer.a === null || answer.b === null) return false;
  if (set.rule.kind === "same") return answer.a === answer.b;
  if (set.rule.kind === "different") return answer.a !== answer.b;
  return answer.a === set.rule.answers[0] && answer.b === set.rule.answers[1];
}
